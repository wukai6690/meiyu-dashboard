      good: ['画了太空主题，但这个题材比较常见——试试加入你想象中的外星生物，不一定要画宇航员', '画面有基本的场景感，但角色之间没有互动——让两个人物之间有眼神交流或动作呼应', '想法是好的但表达方式比较直接，试试用夸张的手法——把开心的嘴巴画到耳朵那么大'],

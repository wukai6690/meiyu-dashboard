// 智能 Mock 评价：基于作品标题关键词模拟真实评价差异
export function smartMockEvaluate(title: string): Record<string, unknown> {
  const seed = title.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  // 基于标题生成确定性的但看起真实的分数分布
  const mockScores = {
    构图: clamp1to3(2 + (seed % 3 === 0 ? 1 : seed % 3 === 1 ? 0 : -1)),
    色彩: clamp1to3(2 + (seed % 5 === 0 ? 1 : seed % 5 <= 2 ? 0 : -1)),
    造型: clamp1to3(2 + (seed % 7 === 0 ? 1 : seed % 7 <= 3 ? 0 : -1)),
    创意: clamp1to3(2 + (seed % 4 === 0 ? 1 : seed % 4 === 1 ? 0 : -1)),
    完整性: clamp1to3(2 + (seed % 6 === 0 ? 1 : seed % 6 <= 2 ? 0 : -1)),
  };

  const dimensionFeedbacks: Record<string, { excellent: string[]; good: string[]; improve: string[] }> = {
    构图: {
      excellent: ['主体突出布局饱满，空间层次处理得当！', '构图均衡有章法，疏密关系把握得很好', '画面布局完整，视觉引导清晰自然'],
      good: ['主体位置基本合理，可以尝试更有张力的构图', '画面布局稳定，增加一些前景元素会让层次更丰富', '构图规整，试试打破对称增加动感'],
      improve: ['物体偏小分散，建议把主体放大集中', '画面有空缺感，适当增加背景元素会更饱满', '构图可以更大胆一些，试试把主体放在黄金分割点'],
    },
    色彩: {
      excellent: ['色调和谐优美，色彩情感表达很到位！', '冷暖搭配恰到好处，涂色细腻均匀', '色彩层次丰富，明暗变化处理得很好'],
      good: ['色彩协调清爽，可以尝试更多渐变层次', '用色明快，适当加入对比色会让画面更有张力', '配色柔和舒适，试试在重点区域用更浓烈的色彩'],
      improve: ['色彩可以更丰富一些，建议多尝试几种颜色的搭配', '涂色还不够均匀，试试单向运笔的方法', '画面色调偏暗，增加一些明亮色彩会让画面更有活力'],
    },
    造型: {
      excellent: ['形态捕捉生动准确，线条流畅有表现力！', '造型结构清晰，比例把握到位', '细节刻画细致，物象特征表现得很好'],
      good: ['造型基本准确，可以加强一些细节的刻画', '形态可以辨认，多观察实物会让造型更生动', '线条比较流畅，尝试用不同粗细的线条丰富表现力'],
      improve: ['建议多观察实物轮廓，先从简单的形状开始练习', '造型还不太确定，可以先轻轻勾出大致轮廓再细化', '线条可以更自信一些，不要怕画错，大胆下笔'],
    },
    创意: {
      excellent: ['创意独特视角新颖，画面叙事感很强！', '想象力丰富，表达方式很有个人风格', '题材有新意，情感表达真挚动人'],
      good: ['想法不错，可以更大胆地展现自己的独特视角', '画面有基本的叙事性，加入更多细节会让故事更生动', '有一定的个人风格，继续保持并多尝试新手法'],
      improve: ['大胆画出你心中的想法，不用太在意画得像不像', '可以试着给画面加入一个有趣的故事或情境', '多观察生活中的有趣瞬间，把它们变成你的创作灵感'],
    },
    完整性: {
      excellent: ['画面完成度很高，每个角落都精心处理！', '细节丰富饱满，边缘处理干净利落', '整体呈现完整统一，看得出投入了很多精力'],
      good: ['主体部分完成得不错，背景也可以再丰富一些', '大部分区域处理得很好，注意画面四角的收尾', '整体完成度可以，再检查一下有没有遗漏的空白区域'],
      improve: ['画面还有空白区域，坚持画完每一处会有意想不到的效果', '建议按先整体后局部的顺序作画，保证画面完整', '先确定主体完成再添加背景，一步步来不着急'],
    },
  };

  const dimKeys = ['构图', '色彩', '造型', '创意', '完整性'] as const;
  const scores = dimKeys.map((k) => ({ key: k, score: mockScores[k] }));

  const totalScore = scores.reduce((s, d) => s + d.score, 0);
  const grade = totalScore >= 14 ? '杰出' : totalScore >= 12 ? '优秀' : totalScore >= 10 ? '良好' : '一般';

  const details = dimKeys.map((dim) => {
    const s = mockScores[dim];
    const level = s >= 3 ? '优秀' : s >= 2 ? '达标' : '待提升';
    const pool =
      s >= 3 ? dimensionFeedbacks[dim].excellent : s >= 2 ? dimensionFeedbacks[dim].good : dimensionFeedbacks[dim].improve;
    const feedback = pool[seed % pool.length];
    return { score: s, level, feedback };
  });

  const overallPool = {
    杰出: [
      '这幅作品展现了出色的艺术感知力和表现技巧！五个维度均有不俗表现，尤其是画面中流露出的真诚与投入最令人欣喜。继续保持这份创作热情，你正在成长为一名出色的小艺术家。',
      '非常出色的作品！构图、色彩和创意都达到了很高的水平，画面充满了艺术感染力。每一笔都看到了你的用心和才华，期待你的更多精彩创作。',
    ],
    优秀: [
      '这件作品整体完成得很好，多个维度表现优秀。画面中有让人眼前一亮的地方，也有可以继续打磨的空间——这正是进步的方向。你对艺术的理解正在不断深化。',
      '很不错的一幅作品！画面整体感强，用色和构图都有亮点。保持这种认真的创作状态，你的艺术表达能力会越来越强。',
    ],
    良好: [
      '作品有扎实的基础表现，部分维度已经展现出了你的潜力。在接下来的练习中，试着多关注构图的层次感和色彩的丰富性，相信你会看到明显的进步。加油！',
      '这幅画完成得不错，有自己的想法在里面。如果在造型细节和画面完整性上再多花些功夫，下一幅作品一定会更精彩。每一次创作都是成长。',
    ],
    一般: [
      '感谢你认真完成了这幅作品！艺术成长需要时间和练习，每一次创作都是宝贵的经验。建议从构图和色彩两个方向着手，多观察、多练习，进步一定会到来的。继续加油！',
      '完成比完美更重要，你已经迈出了创作的第一步。接下来可以试着把主体画大一些、用色更大胆一些。每一幅画都会让你离心中的画面更近一步。',
    ],
  };
  const overall = overallPool[grade][seed % overallPool[grade].length];

  const dimensions: Record<string, { score: number; level: string; feedback: string }> = {};
  details.forEach((d, i) => {
    dimensions[dimKeys[i]] = { score: d.score, level: d.level, feedback: d.feedback };
  });

  return { dimensions, total_score: totalScore, grade, overall_feedback: overall };
}

function clamp1to3(n: number): number {
  return Math.max(1, Math.min(3, n));
}

      good: ['主体人物画得很完整，但背景右下角还留着一块白纸——把背景颜色铺满整个画面', '画面中央区域完成度不错，四个角落还有铅笔草稿线没擦掉——完成画作后检查一遍四个角', '大部分涂色已完成，但细节处（纽扣、鞋带、窗户格子）还是空白——用小号画笔把这些地方补上'],
